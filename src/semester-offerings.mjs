/** 개설 정보가 있는 학생 자율 선택 과목이면 그 학기 개설 여부를, 그 외 과목은 항상 true를 돌려준다. */
export function isOfferedInSemester(course = {}) {
  if (course.selectionGroup !== 'student-choice-pool') return true;
  const offered = SEMESTER_OFFERINGS[Number(course.entryYear)]?.[course.semesterId];
  return offered ? offered.includes(course.subjectName) : true;
}
