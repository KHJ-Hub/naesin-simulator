const object = (value) => Boolean(value) && typeof value === 'object' && !Array.isArray(value);

function normalizedQuickAverages(averages = {}) {
  return Object.fromEntries(Object.entries(object(averages) ? averages : {})
    .map(([semesterId, value]) => [semesterId, Number(value)])
    .filter(([, value]) => Number.isFinite(value) && value >= 1 && value <= 5)
    .sort(([left], [right]) => left.localeCompare(right)));
}

function stableValue(value) {
  if (Array.isArray(value)) return value.map(stableValue);
  if (!object(value)) return value;
  return Object.fromEntries(Object.keys(value).sort().flatMap((key) => value[key] === undefined ? [] : [[key, stableValue(value[key])]]));
}

function meaningfulRecord(record = {}, isAutoGeneratedRecord) {
  const hasScore = Boolean(String(record.gradeValue ?? '').trim() || String(record.achievement ?? '').trim());
  const isManualSelection = Boolean(record.courseId) && !isAutoGeneratedRecord(record);
  if (!hasScore && !isManualSelection) return null;
  return {
    entryYear: Number.isInteger(Number(record.entryYear)) ? Number(record.entryYear) : null,
    semesterId: String(record.semesterId ?? ''),
    courseId: String(record.courseId ?? ''),
    subjectName: String(record.subjectName ?? ''),
    subjectGroup: String(record.subjectGroup ?? ''),
    credit: Number(record.credit) || 0,
    gradingType: String(record.gradingType ?? ''),
    achievementScale: String(record.achievementScale ?? ''),
    requirement: String(record.requirement ?? ''),
    selectionGroup: record.selectionGroup == null ? null : String(record.selectionGroup),
    gradeValue: String(record.gradeValue ?? ''),
    achievement: String(record.achievement ?? ''),
  };
}

/**
 * 학생이 백업으로 보존해야 한다고 느끼는 값만 정규화한다.
 * 아코디언, 스크롤, 입결 검색 필터 같은 일시적 화면 상태는 의도적으로 제외한다.
 */
export function studentBackupDataSnapshot(state = {}, { isAutoGeneratedRecord = () => false } = {}) {
  const actual = (Array.isArray(state.actual) ? state.actual : [])
    .map((record) => meaningfulRecord(record, isAutoGeneratedRecord))
    .filter(Boolean)
    .sort((left, right) => JSON.stringify(left).localeCompare(JSON.stringify(right)));
  const quickAverages = normalizedQuickAverages(state.quickAverages);
  const activeSemesters = new Set([
    ...Object.keys(quickAverages),
    ...actual.map((record) => record.semesterId),
  ]);
  const inputModes = Object.fromEntries(Object.entries(object(state.inputModes) ? state.inputModes : {})
    .filter(([semesterId, mode]) => activeSemesters.has(semesterId) && (mode === 'quick' || mode === 'detailed'))
    .sort(([left], [right]) => left.localeCompare(right)));

  return stableValue({
    student: {
      studentId: String(state.student?.studentId ?? ''),
      studentName: String(state.student?.studentName ?? ''),
    },
    actual,
    quickAverages,
    inputModes,
    targetAverage: String(state.targetAverage ?? ''),
    weighted: state.weighted !== false,
    admissionInterests: Array.isArray(state.admissionInterests)
      ? state.admissionInterests.map(stableValue).sort((left, right) => JSON.stringify(left).localeCompare(JSON.stringify(right)))
      : [],
  });
}

export function createStudentBackupFingerprint(state = {}, options = {}) {
  return JSON.stringify(studentBackupDataSnapshot(state, options));
}

export function isStudentBackupDirty(baselineFingerprint, state = {}, options = {}) {
  return String(baselineFingerprint ?? '') !== createStudentBackupFingerprint(state, options);
}

export function shouldWarnBeforeUnload(isDirty) {
  return Boolean(isDirty);
}
